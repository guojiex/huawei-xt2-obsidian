#!/usr/bin/env python3
"""Generate offline prototype/App sample data from the shared Markdown vault."""
import argparse
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'sample_vault'
BEGIN = '  /* SAMPLE_VAULT_BEGIN: generated by tools/generators/build_sample_vault.py */'
END = '  /* SAMPLE_VAULT_END */'
V2_BEGIN = '/* SAMPLE_VAULT_V2_BEGIN: generated by tools/generators/build_sample_vault.py */'
V2_END = '/* SAMPLE_VAULT_V2_END */'


def quoted(value):
    return json.dumps(value, ensure_ascii=False).replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')


def outputs():
    manifest = json.loads((SOURCE / 'manifest.json').read_text(encoding='utf-8'))
    entries = manifest['notes']
    assert len({item['id'] for item in entries}) == len(entries)
    assert manifest['entry'] in {item['id'] for item in entries}
    paths = [item['path'] for item in entries] + manifest['assets']
    assert len(paths) == len(set(paths))
    bodies = {}
    for rel in paths:
        p = Path(rel)
        assert not p.is_absolute() and '..' not in p.parts and not any(x.startswith('.') for x in p.parts), rel
        bodies[rel] = (SOURCE / 'notes' / p).read_text(encoding='utf-8')
    actual = {p.relative_to(SOURCE / 'notes').as_posix() for p in (SOURCE / 'notes').rglob('*') if p.is_file()}
    assert actual == set(paths), (actual - set(paths), set(paths) - actual)

    tree = []
    seen = set()
    files, content, meta = {}, {}, {}
    for item in entries:
        parts = Path(item['path']).parts
        for depth in range(len(parts) - 1):
            parent = '/'.join(parts[:depth + 1])
            if parent not in seen:
                tree.append(['dir', parts[depth], True, depth])
                seen.add(parent)
        tree.append(['file', parts[-1], False, len(parts) - 1, item['id']])
        files[item['id']] = parts[-1]
        content[item['id']] = bodies[item['path']]
        meta[item['id']] = f"样例 · {len(bodies[item['path']])} 字符"
    vaults = [{'id': 'local', 'name': '本地笔记', 'type': 'local', 'dir': 'vaults/local', 'files': len(entries)}]
    prototype_notes = []
    for item in entries:
        path = Path(item['path'])
        prototype_notes.append({
            'id': item['id'], 'vault': 'local', 'folder': path.parent.as_posix() if path.parent.as_posix() != '.' else '',
            'title': path.stem, 'sub': '', 'tag': '', 'text': bodies[item['path']], 'deleted': False
        })
    trees = {'local': tree}
    for vault in manifest.get('prototype_vaults', []):
        vid = vault['id']
        assert vid not in trees and vid.isalnum(), vid
        selected = vault['note_ids']
        assert len(set(selected)) == len(selected) and set(selected) <= set(files)
        rows, parents = [], set()
        for item in entries:
            if item['id'] not in selected:
                continue
            parts = Path(item['path']).parts
            for depth in range(len(parts) - 1):
                parent = '/'.join(parts[:depth + 1])
                if parent not in parents:
                    rows.append(['dir', parts[depth], True, depth])
                    parents.add(parent)
            note_id = vid + '_' + item['id']
            assert note_id not in files
            rows.append(['file', parts[-1], False, len(parts) - 1, note_id])
            files[note_id], content[note_id], meta[note_id] = files[item['id']], content[item['id']], meta[item['id']]
        trees[vid] = rows
        vaults.append({'id': vid, 'name': vault['name'], 'type': 'local', 'dir': 'vaults/' + vid, 'files': len(selected)})
        for item in entries:
            if item['id'] not in selected:
                continue
            path = Path(item['path'])
            prototype_notes.append({
                'id': vid + '_' + item['id'], 'vault': vid,
                'folder': path.parent.as_posix() if path.parent.as_posix() != '.' else '',
                'title': path.stem, 'sub': '', 'tag': '', 'text': bodies[item['path']], 'deleted': False
            })
    assets = {rel: 'data:image/svg+xml;base64,' + base64.b64encode(bodies[rel].encode()).decode() for rel in manifest['assets']}
    block = '\n'.join([
        BEGIN,
        '  var VAULTS = ' + quoted(vaults) + ';',
        "  var currentVault = 'local';",
        '  var TREES = ' + quoted(trees) + ';',
        '  var FILES = ' + quoted(files) + ';',
        '  var META = ' + quoted(meta) + ';',
        '  var CONTENT = ' + quoted(content) + ';',
        '  var SAMPLE_ASSETS = ' + quoted(assets) + ';',
        END,
    ])
    default_vault = manifest.get('prototype_vaults', [{}])[0].get('id', 'local')
    default_notes = [row['id'] for row in prototype_notes if row['vault'] == default_vault]
    prototype_data = {
        'vaults': vaults, 'notes': prototype_notes, 'assets': assets,
        'defaultVault': default_vault,
        'entryNote': default_notes[0] if default_notes else next(row['id'] for row in prototype_notes if row['vault'] == 'local'),
        'referenceNote': default_notes[1] if len(default_notes) > 1 else (default_notes[0] if default_notes else '')
    }
    v2_block = '\n'.join([
        V2_BEGIN,
        'const SAMPLE_VAULT = ' + quoted(prototype_data) + ';',
        'const notes = SAMPLE_VAULT.notes;',
        'const publicSampleNotes = SAMPLE_VAULT.notes.map(n=>({id:n.id,vault:n.vault,folder:n.folder}));',
        'let libraries = SAMPLE_VAULT.vaults.map(v=>({...v}));',
        'let activeVault = SAMPLE_VAULT.defaultVault;',
        'let current = SAMPLE_VAULT.entryNote;',
        'let reference = SAMPLE_VAULT.referenceNote;',
        "icons.folder='<path d=\"M3 7a2 2 0 0 1 2-2h5l2 2h7a2 2 0 0 1 2 2v10H3z\"/>';",
        "icons.folderOpen='<path d=\"M3 10V7a2 2 0 0 1 2-2h5l2 2h7v3M3 10h19l-3 9H3z\"/>';",
        "icons.chevron='<path d=\"m9 5 7 7-7 7\"/>';",
        "let viewport='wide';const vaultState={},folderState={};",
        V2_END,
    ])
    prototype = ROOT / 'docs/prototype/v2/index.html'
    html = prototype.read_text(encoding='utf-8')
    if V2_BEGIN in html:
        start = html.index(V2_BEGIN)
        # Replace the whole generated prelude. Older drafts left duplicate
        # icon and layout state declarations after the end marker.
        stop = html.index('const currentNotes=', start)
    else:
        start = html.index('const notes=[')
        stop = html.index('const currentNotes=', start)
    html = html[:start] + v2_block + '\n' + html[stop:]
    ets = ['// Generated by tools/generators/build_sample_vault.py; edit sample_vault/notes instead.',
           'export interface SampleVaultFile {', '  path: string;', '  content: string;', '}',
           'export const SAMPLE_VAULT_FILES: SampleVaultFile[] = [']
    for rel in paths:
        ets.append('  { path: ' + quoted(rel) + ', content: ' + quoted(bodies[rel]) + ' },')
    ets.append('];\n')
    return {prototype: html, ROOT / 'entry/src/main/ets/model/SampleVaultData.ets': '\n'.join(ets)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text(encoding='utf-8') != text:
                stale.append(str(p.relative_to(ROOT)))
        else:
            with p.open('w', encoding='utf-8', newline='\n') as output:
                output.write(text)
            print('Generated', p.relative_to(ROOT))
    if stale:
        raise SystemExit('Generated sample data out of date: ' + ', '.join(stale))
    if args.check:
        print('Sample manifest and generated prototype/App data match')


if __name__ == '__main__':
    main()
