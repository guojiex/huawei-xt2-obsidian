#!/usr/bin/env python3
"""Generate the built-in Agent prompt and defaults used by the native app."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'agent/prompts/reading_coach.md'
NATIVE_TARGET = ROOT / 'entry/src/main/ets/model/AgentDefaults.ets'


def native_output():
    prompt = SOURCE.read_text(encoding='utf-8')
    skills = json.loads((ROOT / 'agent/skills/builtin.json').read_text(encoding='utf-8'))
    scenarios = json.loads((ROOT / 'agent/mock/scenarios.json').read_text(encoding='utf-8'))

    def safe(value):
        return json.dumps(value, ensure_ascii=False).replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')

    revision = 'sha256:' + hashlib.sha256(prompt.encode()).hexdigest()
    return (
        '// Generated by tools/generators/build_agent_prompt.py; edit the source files under agent/.\n'
        "import { AgentScenario, AgentSkillDefault } from './AgentModels';\n\n"
        + 'export const BUILTIN_AGENT_PROMPT: string = ' + safe(prompt) + ';\n'
        + 'export const BUILTIN_AGENT_PROMPT_REVISION: string = ' + safe(revision) + ';\n'
        + 'export const BUILTIN_AGENT_SKILLS: AgentSkillDefault[] = ' + safe(skills) + ';\n'
        + 'export const AGENT_MOCK_SCENARIOS: AgentScenario[] = ' + safe(scenarios) + ';\n'
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    native = native_output()
    if args.check:
        if not NATIVE_TARGET.exists() or NATIVE_TARGET.read_text(encoding='utf-8') != native:
            raise SystemExit('Generated native Agent defaults are out of date')
        print('Native Agent defaults, Skills and scenarios match')
    else:
        NATIVE_TARGET.write_text(native, encoding='utf-8', newline='\n')
        print('Generated', NATIVE_TARGET.relative_to(ROOT))


if __name__ == '__main__':
    main()
