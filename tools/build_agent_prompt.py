#!/usr/bin/env python3
"""Embed the versioned built-in Agent prompt into the offline prototype."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'agent/prompts/reading_coach.md'
TARGET = ROOT / 'docs/prototype/index.html'
BEGIN = '  /* AGENT_PROMPT_BEGIN: generated by tools/build_agent_prompt.py */'
END = '  /* AGENT_PROMPT_END */'


def output():
    prompt = SOURCE.read_text()
    assert prompt.strip(), 'Built-in prompt must not be empty'
    data = {'id': 'reading-coach', 'name': '读书讨论',
            'revision': 'sha256:' + hashlib.sha256(prompt.encode()).hexdigest(), 'text': prompt}
    encoded = json.dumps(data, ensure_ascii=False).replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    skills = json.loads((ROOT / 'agent/skills/builtin.json').read_text())
    scenarios = json.loads((ROOT / 'agent/mock/scenarios.json').read_text())
    assert len({skill['id'] for skill in skills}) == len(skills)
    triggers = [text for scene in scenarios for text in scene['inputs']]
    assert len(triggers) == len(set(triggers))
    def safe(value):
        return json.dumps(value, ensure_ascii=False).replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    block = (BEGIN + '\n  var BUILTIN_AGENT_PROMPT = ' + encoded + ';\n'
             + '  var BUILTIN_AGENT_SKILLS = ' + safe(skills) + ';\n'
             + '  var AGENT_MOCK_SCENARIOS = ' + safe(scenarios) + ';\n' + END)
    html = TARGET.read_text()
    if BEGIN in html:
        start = html.index(BEGIN)
        stop = html.index(END, start) + len(END)
        return html[:start] + block + html[stop:]
    return html.replace('  /* AGENT_CONFIG_BEGIN */', block + '\n\n  /* AGENT_CONFIG_BEGIN */', 1)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = output()
    assert BEGIN in result, 'Agent config anchor not found'
    if args.check:
        if TARGET.read_text() != result:
            raise SystemExit('Generated Agent prompt is out of date')
        print('Built-in Agent prompt and prototype match')
    else:
        TARGET.write_text(result)
        print('Generated', TARGET.relative_to(ROOT))


if __name__ == '__main__':
    main()
