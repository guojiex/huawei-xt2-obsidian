#!/usr/bin/env python3
"""Build local changelog views; no network access and no package-version mutation."""
import argparse
from datetime import date
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
LABELS = {'in_progress': '开发中', 'implemented': '已实现 · 未发布', 'pending': '暂缓 · 未发布', 'released': '已发布'}
RECENT_LIMIT = 3


def validate(data):
    if data.get('schemaVersion') != 1 or not isinstance(data.get('entries'), list):
        raise ValueError('Expected schemaVersion 1 and entries array')
    seen = set()
    for entry in data['entries']:
        version = entry.get('version', '')
        if not isinstance(version, str) or not re.fullmatch(r'\d+\.\d+\.\d+', version) or version in seen:
            raise ValueError('Invalid or duplicate version: ' + str(version))
        seen.add(version)
        if entry.get('status') not in LABELS:
            raise ValueError('Unknown status: ' + str(entry.get('status')))
        date.fromisoformat(entry['date'])
        if not isinstance(entry.get('title'), str) or not entry['title'].strip():
            raise ValueError('Missing title')
        if not isinstance(entry.get('changes'), list) or not entry['changes'] or any(not isinstance(x, str) or not x.strip() for x in entry['changes']):
            raise ValueError('Changes must be nonempty strings')
    return sorted(data['entries'], key=lambda item: tuple(map(int, item['version'].split('.'))), reverse=True)


def recent(entries):
    return [entry for entry in entries if entry['status'] != 'pending'][:RECENT_LIMIT]


def quoted(value):
    # Safe when embedded in HTML <script>, including authored release-note text.
    return json.dumps(value, ensure_ascii=False).replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')


def package_version():
    # Read only these stable fields from the existing commented JSON5; never rewrite it.
    text = (ROOT / 'AppScope/app.json5').read_text()
    return re.search(r'"versionName"\s*:\s*"([^"\n]+)"', text)[1], int(re.search(r'"versionCode"\s*:\s*(\d+)', text)[1])


def outputs():
    entries = validate(json.loads((ROOT / 'changelog.json').read_text()))
    expanded = [{**entry, 'statusLabel': LABELS[entry['status']]} for entry in entries]
    version, build = package_version()
    ets = '''// Generated by tools/build_changelog.py; edit changelog.json instead.
export interface ChangelogEntry {
  version: string;
  date: string;
  status: string;
  statusLabel: string;
  title: string;
  changes: string[];
}
export const CHANGELOG_ENTRIES: ChangelogEntry[] = [
'''
    for entry in expanded:
        ets += '  ' + quoted(entry) + ',\n'
    ets += '];\nexport const RECENT_CHANGELOG: ChangelogEntry[] = CHANGELOG_ENTRIES.filter(\n  (entry: ChangelogEntry): boolean => entry.status !== \'pending\').slice(0, ' + str(RECENT_LIMIT) + ');\n'
    markdown = '# 版本记录\n\n> 由 `changelog.json` 生成，运行 `python3 tools/build_changelog.py` 更新。日期为阶段记录日期；只有标记“已发布”的条目表示正式发布。\n'
    for entry in entries:
        markdown += '\n## v' + entry['version'] + ' · ' + entry['title'] + '\n\n' + entry['date'] + ' · ' + LABELS[entry['status']] + '\n\n'
        markdown += '\n'.join('- ' + item for item in entry['changes']) + '\n'
    return {ROOT / 'entry/src/main/ets/model/ChangelogData.ets': ets, ROOT / 'CHANGELOG.md': markdown}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
            print('Generated', path.relative_to(ROOT))
    if stale:
        raise SystemExit('Changelog generated output is stale: ' + ', '.join(stale))
    if args.check:
        print('Changelog data, package preview version and generated outputs match')


if __name__ == '__main__':
    main()
